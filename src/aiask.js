const AIE_AROUND = 8, AIE_OUT_MAX = 5000, AIE_OUT_LINES = 60;

/** Строки вокруг номера строки (с 1) и границы показа. */
function aiExcerpt(text, line, around) {
  const L = String(text || '').replace(/\r\n?/g, '\n').split('\n'), n = Math.max(1, Math.min(L.length, +line || 1)), k = around == null ? AIE_AROUND : around;
  const a = Math.max(1, n - k), b = Math.min(L.length, n + k);
  return { text: L.slice(a - 1, b).join('\n'), from: a, to: b, at: n, total: L.length };
}
/** Что за ошибка и какой кусок кода уйдут вместе с вопросом: готовые пункты для чата. */
function aiCodeItem(path, text, line, extra) {
  const x = aiExcerpt(text, line), rows = t('aie.c.rows', x.from, x.to);
  return { id: 'code', label: t('aie.c.code', path + ', ' + rows), title: 'Фрагмент ' + path + ' (строки ' + x.from + '–' + x.to + (line ? ', ошибка в строке ' + x.at : '') + ')' + (extra || ''), lang: 'renpy', text: x.text, on: true };
}
/** Общий вход: открывает окно кода и передаёт вопрос. spec: {q, items, on, noFile, send, file, line}. */
function aiAskError(spec) {
  if (typeof openIde !== 'function') return null;
  return openIde({ file: spec.file || undefined, line: spec.line || 0, ask: Object.assign({ send: true }, spec) });
}

/** Из строки отчёта сборки: текст ошибки + фрагмент скрипта главы вокруг строки. Без номера строки добавляется сводка проекта. */
function aiAskBuild(it) {
  const n = it.nodeId ? nodeById(it.nodeId) : null, f = n && it.fileId ? (n.files || []).find(x => x.id === it.fileId) : null;
  const items = [{ id: 'err', label: t('aie.c.err'), title: 'Сообщение программы при сборке (' + (it.level === 'error' ? 'ошибка' : 'предупреждение') + ')', lang: '', text: String(it.msg || ''), on: true }];
  if (f && it.line) {
    const nm = (typeof rsFileTitle === 'function' ? rsFileTitle(n, f) : '') || n.title || '';
    items.push(aiCodeItem('«' + nm + '»', f.script, it.line, ' скрипта главы'));
  }
  return aiAskError({ q: t('aie.q.build'), items, on: { proj: !(f && it.line) }, noFile: true });
}

/** Последний блок ошибки в выводе консоли Ren'Py: от последнего «Traceback» или строки с Error/Exception, не длиннее AIE_OUT_LINES строк. */
function aiRpErrorBlock(lines) {
  const arr = (lines || []).filter(l => l.s !== 'sys');
  let from = -1;
  for (let i = arr.length - 1; i >= 0; i--) { if (/Traceback \(most recent call last\)/.test(arr[i].text)) { from = i; break; } }
  if (from < 0) for (let i = arr.length - 1; i >= 0; i--) { if (/\b(\w*Error|Exception)\b|error:|\.rpy:\d+|line \d+/i.test(arr[i].text) && (arr[i].s === 'err' || /Error|Exception|error|не удалось|Failed/i.test(arr[i].text))) { from = i; while (from > 0 && /^\s|^File /.test(arr[from - 1].text)) from--; break; }
  }
  if (from < 0) return null;
  const blk = arr.slice(from, from + AIE_OUT_LINES).map(l => l.text);
  return blk.join('\n').trim() ? blk : null;
}
/** Из консоли: вывод ошибки + фрагмент файла вокруг последней ссылки на строку; файл открывается в окне кода на этой строке. */
function aiAskRenpy() {
  const blk = aiRpErrorBlock(RP.out);
  if (!blk) { toast(t('aie.rp.none'), 3500); return null; }
  let ref = null;
  for (const l of blk) { const r = rpFindRef(l); if (r) ref = r; }                                // ближе к причине последняя ссылка (так устроен traceback Python)
  const out = aiClip(blk.join('\n'), AIE_OUT_MAX);
  const items = [{ id: 'err', label: t('aie.c.out', t('aic.lines', blk.length)), title: 'Вывод Ren\'Py с ошибкой', lang: '', text: out.text, cut: out.cut, on: true }];
  let q = t('aie.q.rp'), hit = null, haveCode = false;
  if (ref) {
    const f = RP.R && (RP.R.files || []).find(x => x.path === ref.file);
    hit = RP.map ? rpBlockAt(RP.map, ref.file, ref.line) : null;
    if (f && f.text) { items.push(aiCodeItem(ref.file, f.text, ref.line)); haveCode = true; }
    if (hit && /^game\/story\//.test(ref.file)) q += ' ' + t('aie.q.gen', hit.b.title);
  }
  return aiAskError({ q, items, on: { proj: !haveCode }, noFile: haveCode, file: ref ? ref.file : '', line: ref ? ref.line : 0 });
}
